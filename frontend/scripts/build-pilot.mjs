#!/usr/bin/env node
/* The gym pilot's product build, from explicit inputs (docs/ops/PILOT_MOBILE_RELEASE.md):
 *
 *   PILOT_PRODUCT=../deploy/pilot/product.example.json node scripts/build-pilot.mjs [--out dist-pilot]
 *   PILOT_PRODUCT=… node scripts/build-pilot.mjs --mobile     # into dist/, then cap sync android
 *
 * The product file names the app, its application id, its https server, the media mode and the
 * source offer (check-pilot-bundle.mjs validateProduct). Upstream builds and files are untouched:
 * the web build goes to its own directory, and the Android identity is a generated, ignored
 * android/pilot.properties that build.gradle reads only when it exists.
 *
 * Media: "placeholder" stages no exercise media at all (the app shows its fallback); "licensed"
 * stages exactly the files of the licensed manifest (scripts/catalogue/stage-media.mjs
 * --manifest). The bundle checker runs last and fails the build on any problem. */
import fs from 'node:fs'
import path from 'node:path'
import { spawnSync } from 'node:child_process'
import { fileURLToPath } from 'node:url'
import { validateProduct, checkPilotBundle } from './check-pilot-bundle.mjs'

const FRONTEND = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const args = process.argv.slice(2)
const mobile = args.includes('--mobile')
const at = args.indexOf('--out')
const out = path.resolve(FRONTEND, mobile ? 'dist' : at >= 0 ? args[at + 1] : 'dist-pilot')
const fail = msg => { console.error('build-pilot: ' + msg); process.exit(1) }
const run = (cmd, argv, env = {}) => {
  const r = spawnSync(cmd, argv, { cwd: FRONTEND, stdio: 'inherit', env: { ...process.env, ...env } })
  if (r.status !== 0) fail(`${cmd} ${argv.join(' ')} failed`)
}

const productFile = process.env.PILOT_PRODUCT
if (!productFile) fail('set PILOT_PRODUCT to the product file (deploy/pilot/product.example.json shows its fields)')
let product
try { product = JSON.parse(fs.readFileSync(path.resolve(FRONTEND, productFile), 'utf8')) } catch { fail(`cannot read ${productFile}`) }
if (product.media?.manifest) product.media.manifest = path.resolve(path.dirname(path.resolve(FRONTEND, productFile)), product.media.manifest)
const invalid = validateProduct(product)
if (invalid.length) fail('the product file is not usable:\n  ' + invalid.join('\n  '))
const version = JSON.parse(fs.readFileSync(path.join(FRONTEND, 'package.json'), 'utf8')).version

// Placeholder: the media addresses point at nothing the build ships, so no restricted file is
// requested from anywhere and the app's fallback shows.
const mediaEnv = product.media.mode === 'placeholder'
  ? { VITE_IMG_BASE: 'exercise-media-unavailable/', VITE_GIF_BASE: 'exercise-media-unavailable/' }
  : {}
run(process.execPath, [path.join(FRONTEND, 'node_modules/vite/bin/vite.js'), 'build', '--outDir', out, '--emptyOutDir'], {
  VITE_PILOT: '1', VITE_PILOT_SERVER: product.server, ...(mobile ? { VITE_MOBILE: '1' } : {}), ...mediaEnv,
})
if (product.media.mode === 'licensed') run(process.execPath, [path.join(FRONTEND, '../scripts/catalogue/stage-media.mjs'), out, '--manifest', product.media.manifest])

// Branding and the source offer for this exact version.
const manifestFile = path.join(out, 'manifest.json')
if (fs.existsSync(manifestFile)) {
  const m = JSON.parse(fs.readFileSync(manifestFile, 'utf8'))
  fs.writeFileSync(manifestFile, JSON.stringify({ ...m, name: product.productName, short_name: product.productName }, null, 2))
}
const indexFile = path.join(out, 'index.html')
fs.writeFileSync(indexFile, fs.readFileSync(indexFile, 'utf8').replace(/<title>[^<]*<\/title>/, `<title>${product.productName.replace(/[<&]/g, '')}</title>`))
fs.writeFileSync(path.join(out, 'OPEN-SOURCE.txt'), [
  `${product.productName} ${version}`,
  'Licence: AGPL-3.0-or-later.',
  `Based on openGym: ${product.source.upstream}`,
  `Source for this version (${version}): ${product.source.offerUrl.replace('{version}', version)}`,
  '',
].join('\n'))
fs.writeFileSync(path.join(out, 'pilot-build.json'), JSON.stringify({
  productName: product.productName, appId: product.appId, server: product.server,
  media: { mode: product.media.mode }, version, builtAt: new Date().toISOString(),
}, null, 2))

let androidDir
if (mobile) {
  androidDir = path.join(FRONTEND, 'android')
  fs.writeFileSync(path.join(androidDir, 'pilot.properties'), `# Generated by scripts/build-pilot.mjs; not committed.\napplicationId=${product.appId}\nappLabel=${product.productName}\n`)
  run(path.join(FRONTEND, 'node_modules/.bin/cap'), ['sync', 'android'])
}

const problems = checkPilotBundle({ webDir: out, product, version, androidDir })
if (problems.length) fail('the bundle failed its gates:\n  ' + problems.join('\n  '))
console.log(`build-pilot: ${product.productName} ${version} (${product.media.mode} media) -> ${path.relative(FRONTEND, out)}${mobile ? ' + android' : ''}`)
